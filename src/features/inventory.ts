export function dropsFor(egg: number): Drop[] {
  const rows = eggPools[egg] ?? commonMysteryPool;
  const hasShards = rows.some(([id]) => id === 51);
  if (hasShards) {
    return rows;
  }
  const sum = rows.reduce((acc, [, chance]) => acc + chance, 0);
  const remainder = Math.max(0, 100 - sum);
  return remainder > 1e-9 ? [...rows, [51, remainder, '1/5'] as const] : rows;
}

