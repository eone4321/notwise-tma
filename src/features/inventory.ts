export function dropsFor(egg: number): Drop[] {
  const rows = eggPools[egg];
  const remainder = 100 - rows.reduce((sum, [, chance]) => sum + chance, 0);
  return [...rows, ...(remainder > 1e-9 ? [[51, remainder] as const] : [])].sort((a, b) => b[1] - a[1]);
}

